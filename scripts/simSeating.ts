// 对镜类模拟的**座位与先后手**编排,单独一个模块 —— 因为这里踩过两次同一个坑。
//
// 【坑长什么样】
// 想「让两边轮流坐先后手」,顺手写成:
//   const seat  = i & 1
//   const seed  = i * 131 + 7
//   const first = seed & 1        // ← 灾难
// 131 是奇数,于是 seed 的奇偶与 i 的奇偶同步翻转,`first` 就恒等于 `1 - seat` ——
// **被测的那一方永远后手**,一局先手都没坐过。注释写着「轮流坐先后手」,
// 实际只轮换了座位,先后手被绑死在反面。
//
// 【为什么后果这么重】
// 这游戏的先手优势极大:自我对镜(同一个主公、同一副牌、同一个 AI,
// 唯一的不对称只剩谁先手)实测后手只有 **24–29%** 胜率,而不是 50%。
// 起手牌已经补过了(先手 3 张、后手 4 张,见 engine/init),仍然差这么多。
// 也就是说带着这个 bug 的闸门,中性点不是 50% 而是约 26%,
// 而它还在拿 40–60% 去判定 —— 每一个数字都是废的。
//
// 【它真的发生过两次】
// sim-balance 早就踩过并修好了(见那个文件顶部的注释),
// 但 sim-hero-mirror 一字不差地又写了一遍,而且带着这把歪尺子
// 劝退过两轮主公技设计(见 overrides/heroes.ts 里 呂蒙 那一段)。
// 所以这次不只是改对,而是把不变量抽出来钉进单测:simSeating.test.ts。
//
// 【规则】座位与先后手必须**各自独立**地轮换,四种组合等量出现。
// 用 i 的第 0 位定座位、第 1 位定先手,四局一个周期。
// 因此**局数取 4 的倍数**,四种组合才跑得齐(与 sim-balance 同一条要求)。

export interface Seating {
  /** 被测方(备选主公)坐哪个座位 */
  altSeat: 0 | 1
  /** 哪个座位先手 —— 必须与 altSeat 无关 */
  first: 0 | 1
}

export function seatingFor(i: number): Seating {
  return { altSeat: (i & 1) as 0 | 1, first: ((i >> 1) & 1) as 0 | 1 }
}
