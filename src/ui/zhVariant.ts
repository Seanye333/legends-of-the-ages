// 繁 → 简。
//
// 【为什么需要它】
// 这个项目的中文有**两个来源**:界面文案是手写的(简体),
// 卡池文案是从姊妹仓库导入的(繁體)。于是同一个屏幕上
// 「结束回合」和「戰吼:對一名敵將造成 3 點傷害」并排出现 ——
// 两种字形混排,读起来像两个人拼起来的软件。
//
// 【为什么只做繁→简,不做简→繁】
// 这一条是整个模块最重要的设计决定。
//
// 繁→简 是**多对一**:「發」和「髮」都简作「发」,「隻」和「只」都简作「只」。
// 多对一是纯查表,不需要理解上下文,永远不会错。
//
// 简→繁 是**一对多**:「发」到底是「發」还是「髮」,得看它在哪个词里。
// 没有分词和词典的话,「头发」会变成「頭發」,「发财」会变成「髮財」——
// 而且**错得看不出来**:字都是对的,只是用错了那一个。
// 所以这个方向这里**不做**。想看繁體的人直接看原文(卡池本来就是繁體)。
//
// 【表是精选的,不是穷尽的】
// 卡池里有 2,259 个不同的汉字,其中绝大多数繁简同形。这张表覆盖的是
// **实际出现在卡面与列传里**的那些异形字。没覆盖到的字原样透出 ——
// 失败模式是「这一个字还是繁體」,而不是「这个字变错了」。
// `npm run audit-zh` 会报出当前的覆盖情况。
//
// 【为什么不引第三方库】
// opencc 之类的完整方案是 1MB 级的数据。这个游戏的首屏预算只剩 25KB,
// 而它换来的只是把「几个字没转」变成「一个字都不剩」。不划算。

