// 词条(多字)优先于单字:表里既有「發」→「发」也有「發現」→「发现」,
// 逐字替换的话两者结果相同,但保留词条让将来能处理那些**必须看词才对**的情况。
const MULTI = Object.keys(TABLE)
  .filter((k) => k.length > 1)
  .sort((a, b) => b.length - a.length)

/** 繁 → 简。表里没有的字原样透出(见文件头:失败模式是「没转」,不是「转错」)。 */
export function toSimplified(text: string): string {
  let out = text
  for (const k of MULTI) {
    if (out.includes(k)) out = out.split(k).join(TABLE[k])
  }
  let res = ''
  for (const ch of out) res += TABLE[ch] ?? ch
  return res
}

/** 这张表一共覆盖多少个字形(给盘点脚本用)。 */
export function variantTableSize(): number {
  return Object.keys(TABLE).length
}

/** 表里的全部键(给盘点脚本算覆盖率用)。 */
export function variantKeys(): string[] {
  return Object.keys(TABLE)
}
