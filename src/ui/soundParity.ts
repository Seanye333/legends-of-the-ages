// 静音优先 —— 每一个音效都必须有一个**非听觉**的对应通道。
//
// 【为什么要有这张表】
// 手机玩家里有相当一部分从不开声音(通勤、办公室、孩子睡了)。
// 如果某个信息只有声音说得出来,这些人玩的就是一个残缺的游戏 ——
// 而这种缺失**不会有人报 bug**,因为开发的人自己一直开着声音。
//
// 这张表把「这条信息还有别的通道」从口头约定变成**编译期约束**:
// `Record<SfxName, string>` 是穷尽的,新增一个音效而不填这一格,`tsc` 当场报错。
// 填的内容不是给机器看的,是逼填表的人真的去想一遍「关掉声音还看得见吗」。
//
// 【一条实测】
// 填这张表的过程本身就抓到了问题:抽牌、得甲、发现、羁绊触发四个事件
// 此前**既没有音效也没有独立动效**,只在战报文本里有一行 ——
// 而战报是折叠的。补音效的同时也就补上了它们的视觉通道。
