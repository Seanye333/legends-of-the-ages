// 调平层 —— 实测确认超模的十一张,五轮收敛。
//
// 【这一层为什么和 packN 分开】
// packN 是**内容**(这一批卡是什么);这一层是**数值**(它标错了价)。
// 混在一起的话,下一个人想知道「这张卡被调过没有」得翻二十几个文件。
// 它挂在 `cards.ts` 的**全池**那一层(不是生成层的合并循环)——
// 理由见那里的注释:packN 里直接定义的卡根本不经过那个循环,
// 调平层写在里面对它们完全无效,而且无声无息。实测踩过,十一张里丢了两张。
//
// 【它们是怎么被认出来的,以及为什么定价表没拦住】
// `npm run sim-cards` 扫完全池 2416 张(60 局/张),榜首按 600 局复测。
// 而 `price-cards` 只认为其中少数几张略高 —— 因为定价表**系统性低估节奏型战吼**:
// 弹回手牌、群体点杀这类「不产生卡差、但抢走对手一整个回合」的效果。
// 按 op 归组量出来的偏差:returnToHand +10.1 / aoeDamage +9.4 / recruit +8.8。
// 所以这一轮的尺子用**实测 Δ**,不用定价表 —— 表在这一类效果上正是坏的那把。
//
// 【先验了尺子,再改的卡】
// 「+10 到底算不算超模」需要一条基准线,否则可能是**预组太弱**、
// 任何能打的卡换进去都 +10。所以单独量了五张中立白板武将当对照组
// (没有关键词、没有任何脚本、没有光环羁绊),各 600 局:
//
//   張布 2费 2/3  +6.5   薛珝 3费 4/3  +3.5   朱然 6费 6/6  −1.0
//   陳餘 5费 4/7  −1.2   辛毗 4费 3/6  −4.8            中位 −1.0
//
// 白板贴着 0,**这把尺子没有正偏** —— 于是 +10 是真的远,改得有依据。
// 收工线就按这个对照组的实际跨度(−4.8 ~ +6.5)定,而不是拍一个 ±4。
//
// 【五轮的实测轨迹(全部 600 局;单次测量 SE ±2.0,Δ 是两次之差 SE ±2.9)】
//
//   卡         原始    一轮    二轮    三轮    四轮    五轮
//   華雄       22.2    15.2     9.8    −2.3     2.2          ← 三轮削过头,四轮回调
//   神機營     21.5    12.2     9.5     8.8     5.2
//   姜維       19.2    12.2     7.8
//   曹安民     17.8     9.7     4.8
//   候時而動   17.7    14.3    11.7     3.2
//   簡雍       17.0     9.7     5.5
//   項伯       16.7    14.8     9.2     7.0
//   鄭厲公     15.5     5.2
//   賈復       15.3     6.5
//   陳群       14.3    12.2    11.3     9.3     3.5
//   蘇飛       14.0    11.8    10.0    10.0     9.0     2.0
//
// 【这一路量到的三件事,以后不用再猜】
//
// 1. **+1 费第一格 ≈ −5.0pp**(七张纯涨费是同一个杠杆的七次独立测量:
//    −8.1 / −7.3 / −10.3 / −3.4 / −2.2 / −2.1 / −1.9)。第二格只剩 −3.2,
//    到了 6 费以上**基本失效** —— 蘇飛 5→6 费一动不动(10.0 → 10.0)。
//    高费段该削的是身材和效果,不是费用。
// 2. **同效果的卡会停在同一个地板上**。項伯 与 蘇飛(都是全场 2 伤)不管怎么改
//    费用身材,都卡在 +7~+9 —— 那是「全场 2 伤」这个效果本身的价钱。
//    最后是把这一对**拉开档次**才收住的(蘇飛 改成 4 费的全场 1 伤),不是继续加价。
// 3. **削过头是会发生的,而且只有量了才知道**。華雄 第三轮同时削攻和削战吼,
//    直接掉到 −2.3(比白板还差);第四轮把攻回调一格就回到 +2.2。
//    「一次只动一个旋钮」在这里不是洁癖,是能不能读出因果的分界。
//
// 【传奇按更宽的一档收】
// ≤+8 而不是 ≤+5:`price-cards` 的注释里就写着「传奇本来就该超模」,
// 一张全池独一份的牌本来就该比替补强。
//
// ============================================================
// 【第六轮:后手补偿落地之后**全部重量了一遍**】
//
// 上面那五轮是在**旧规则**下量的。当天晚些时候落地了后手补偿
// (`SECOND_PLAYER_COMP`:后手起手全部手牌 −1 费 + 3 点护甲),
// 而任何全局规则改动都会改变**所有卡的相对价值** —— 所以那五轮的结论
// 不能默认还成立。重量的结果:
//
//   姜維   7.8 → **13.5**   ← 唯一弹回带外(z=4.7)
//   項伯   7.0 →   7.8      陳群   3.5 → 7.2      賈復   6.5 → 6.0
//   曹安民 4.8 →   5.8      蘇飛   2.0 → 3.3      神機營 5.2 → 3.0
//   簡雍   5.5 →   2.8      鄭厲公 5.2 → 1.7
//   華雄   2.2 →  −1.3      候時而動 3.2 → −1.3
//
// 十一张里十张仍在带内(白板对照组的跨度是 −4.8 ~ +6.5),只有 姜維 要再来一轮:
// 身材 4/6 → 3/5,落到 **+7.3**,回到传奇那一档。
//
// **姜維 弹回来是有道理的**:补偿让起手每张牌便宜 1 费,而它是 7 费 ——
// 高费卡吃这份折扣最多。(不过并非所有 7 费卡都涨:賈復 持平、神機營 反而降了,
// 所以这不是一条能外推的规律,只能一张张量。)
//
// 这一段本身就是那条通则的实例:**全局规则一动,先前所有基于实测的结论都要复验。**
// 同理,`sim-cards` 那次全池扫描(2416 张 / 60 局)也是补偿之前跑的,
// 「没有一张越过校正线」那个结论同样需要重跑才算数。
// ============================================================
//
// 【复测】
//   CARDS=<id> GAMES=600 npm run sim-cards
// **这十一张没有一张在预组里**(逐套查过),所以 sim-balance 不受影响 ——
// ROADMAP 里原来写着「这几张里有好几张在预组里」,那句话是错的,已改。
